#!/usr/bin/env python3
"""Convert a TTF into a 1-bpp LovyanGFX GFXfont header.

Usage: fontgen.py <font.ttf> <pixel_size> <C name> <chars> <out.h>

Only `chars` get bitmaps; other code points between the first and last char get an
empty glyph, because GFXfont needs a contiguous range. Keeping `chars` small keeps
flash use (and the header) small.

Source fonts are not committed. JetBrains Mono v2.304 (OFL):
https://raw.githubusercontent.com/JetBrains/JetBrainsMono/v2.304/fonts/ttf/
Requires Pillow (dev machine only; not a firmware dependency).
"""
import sys

from PIL import Image, ImageDraw, ImageFont


def render(font, ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    adv = round(font.getlength(ch))
    if w <= 0 or h <= 0:
        return [], 0, 0, adv, 0, 0
    img = Image.new("1", (w, h), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"  # no anti-aliasing; GFXfont is 1-bpp
    draw.text((-x0, -y0), ch, font=font, anchor="ls", fill=1)
    bits = [1 if img.getpixel((x, y)) else 0 for y in range(h) for x in range(w)]
    data = []
    for i in range(0, len(bits), 8):
        byte = 0
        for b in bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8])):
            byte = (byte << 1) | b
        data.append(byte)
    return data, w, h, adv, x0, y0


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    ttf, size, name, chars, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    codes = sorted({ord(c) for c in chars})
    first, last = codes[0], codes[-1]

    bitmap, glyphs = [], []
    for code in range(first, last + 1):
        if code in codes:
            data, w, h, adv, xo, yo = render(font, chr(code))
        else:
            data, w, h, adv, xo, yo = [], 0, 0, 0, 0, 0
        glyphs.append((len(bitmap), w, h, adv, xo, yo, code))
        bitmap.extend(data)

    lines = [
        "// Generated by firmware/tools/fontgen.py. Do not edit.",
        f"// Source: {ttf.rsplit('/', 1)[-1]} at {size} px (SIL OFL 1.1, see OFL.txt).",
        f"// Glyphs: {''.join(chr(c) for c in codes)!r}",
        "#pragma once",
        "",
        "#include <LovyanGFX.hpp>",
        "",
        f"static const uint8_t {name}_bitmaps[] PROGMEM = {{",
    ]
    for i in range(0, len(bitmap), 24):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"static const lgfx::GFXglyph {name}_glyphs[] PROGMEM = {{")
    row = []
    for off, w, h, adv, xo, yo, _ in glyphs:
        row.append(f"{{{off},{w},{h},{adv},{xo},{yo}}}")
        if len(row) == 6:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"static const lgfx::GFXfont {name}(")
    lines.append(f"    (uint8_t*){name}_bitmaps, (lgfx::GFXglyph*){name}_glyphs,")
    lines.append(f"    0x{first:02X}, 0x{last:02X}, {ascent + descent});")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {len(codes)} glyphs, {len(bitmap)} B bitmap, {len(lines)} lines")


if __name__ == "__main__":
    main()
